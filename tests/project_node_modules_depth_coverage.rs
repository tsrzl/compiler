use std::fs;
use std::path::{Path, PathBuf};
use std::process::{Command, Output};

struct TemporaryProject {
    path: PathBuf,
}

impl TemporaryProject {
    fn new(name: &str) -> Self {
        let path = std::env::temp_dir().join(format!(
            "tsrzl-project-node-modules-depth-{}-{name}",
            std::process::id()
        ));
        fs::create_dir_all(&path).expect("the temporary project directory can be created");
        Self { path }
    }

    fn path(&self) -> &Path {
        &self.path
    }

    fn write(&self, relative_path: &str, contents: &str) {
        let path = self.path.join(relative_path);
        if let Some(parent) = path.parent() {
            fs::create_dir_all(parent).expect("the project fixture directory can be created");
        }
        fs::write(path, contents).expect("the project fixture can be written");
    }

    fn run_cli(&self) -> Output {
        Command::new(env!("CARGO_BIN_EXE_tsrzl"))
            .arg("--project")
            .arg(self.path())
            .output()
            .expect("the compiler CLI can be started")
    }
}

impl Drop for TemporaryProject {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.path);
    }
}

fn max_depth_exceeded_project(name: &str, root_source: &str) -> TemporaryProject {
    let project = TemporaryProject::new(name);
    project.write(
        "tsconfig.json",
        r#"{"compilerOptions":{"allowJs":true,"maxNodeModuleJsDepth":1,"outDir":"built"},"include":["**/*","node_modules/**/*"],"exclude":["node_modules/m2/**/*"]}"#,
    );
    project.write("root.ts", root_source);
    project.write(
        "node_modules/m1/index.js",
        "var m2 = require('m2'); var rel = require('./relative'); exports.f1 = function(p1) { return 42; }; exports.f2 = m2; exports.rel = rel.relativeProp;",
    );
    project.write(
        "node_modules/m1/relative.js",
        "exports.relativeProp = true;",
    );
    project.write("node_modules/m2/package.json", r#"{"main":"entry.js"}"#);
    project.write(
        "node_modules/m2/entry.js",
        "var m3 = require('m3'); module.exports = { a: 42, b: 'hello', person: m3.person };",
    );
    project.write(
        "node_modules/m2/node_modules/m3/index.js",
        "exports.person = { name: 'John Doe', age: 42 };",
    );
    project
}

// Pinned project: projects/NodeModulesSearch/maxDepthIncreased/root.ts.
// Runner: project/nodeModulesMaxDepthIncreased.json (allowJs=true, maxNodeModuleJsDepth=3).
// TS-Go 7.0.2 reports TS2322 when the third nested JavaScript module supplies age: number.
#[test]
fn should_report_nested_javascript_type_mismatch_given_max_node_module_js_depth_three_when_compiling_project()
 {
    // Arrange
    let project = TemporaryProject::new("max-depth-three");
    project.write(
        "tsconfig.json",
        r#"{"compilerOptions":{"allowJs":true,"maxNodeModuleJsDepth":3},"files":["root.ts"]}"#,
    );
    project.write(
        "root.ts",
        "import * as m1 from 'm1'; m1.f2.person.age = '10';",
    );
    project.write(
        "node_modules/m1/index.js",
        "var m2 = require('m2'); exports.f2 = m2;",
    );
    project.write("node_modules/m2/package.json", r#"{"main":"entry.js"}"#);
    project.write(
        "node_modules/m2/entry.js",
        "var m3 = require('m3'); module.exports = { person: m3.person };",
    );
    project.write(
        "node_modules/m2/node_modules/m3/index.js",
        "exports.person = { age: 42 };",
    );

    // Act
    let process = project.run_cli();
    let diagnostics = format!(
        "{}{}",
        String::from_utf8_lossy(&process.stdout),
        String::from_utf8_lossy(&process.stderr)
    );

    // Assert
    assert!(diagnostics.contains("TS2322"), "{diagnostics}");
}

